template <class Recreate>
static void lightning_scene_context_controls(Recreate recreate)
{
	using namespace xl_compat;
	ParticleImageResource image;
	image.bitmap.width = image.bitmap.height = 16;
	image.bitmap.truecolor = true;
	image.bitmap.pixels.resize(16 * 16 * 4, 127);
	image.texture = std::make_unique<ParticleTexture>(image.bitmap, "retained-lightning-corona");
	grs_screen screen{};
	screen.sc_w = screen.sc_h = 64;
	grd_curscreen = &screen;
	View_position = {};
	View_matrix = { { 65536, 0, 0 }, { 0, 65536, 0 }, { 0, 0, 65536 } };
	const std::vector<LightningPoint> nodes{ { -32768, -16384, 196608 }, { 0, 19661, 196608 }, { 32768, -6554, 196608 }, { 40000, 10000, 196608 } };
	LightningSceneItem item{};
	item.frame.core = lightning_core_geometry(nodes, [](const LightningVertex &p) { return p[2]; });
	item.frame.glow = lightning_glow_geometry(nodes, 1, .7f, true, { 0, 0, 0 }, 3, 4999);
	item.random_nodes = 1;
	item.width = .7f;
	item.color = { .1f, .3f, .5f, .5f };
	const auto draw = [&] {
		GLuint target, color, scene_depth;
		glGenFramebuffers(1, &target);
		glGenTextures(1, &color);
		glGenRenderbuffers(1, &scene_depth);
		glBindFramebuffer(GL_FRAMEBUFFER, target);
		glBindTexture(GL_TEXTURE_2D, color);
		glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA8, 64, 64, 0, GL_RGBA, GL_UNSIGNED_BYTE, nullptr);
		glFramebufferTexture2D(GL_FRAMEBUFFER, GL_COLOR_ATTACHMENT0, GL_TEXTURE_2D, color, 0);
		glBindRenderbuffer(GL_RENDERBUFFER, scene_depth);
		glRenderbufferStorage(GL_RENDERBUFFER, GL_DEPTH_COMPONENT24, 64, 64);
		glFramebufferRenderbuffer(GL_FRAMEBUFFER, GL_DEPTH_ATTACHMENT, GL_RENDERBUFFER, scene_depth);
		check(glCheckFramebufferStatus(GL_FRAMEBUFFER) == GL_FRAMEBUFFER_COMPLETE, "Native lightning scene target incomplete");
		glViewport(3, 5, 48, 43);
		glMatrixMode(GL_PROJECTION);
		glLoadIdentity();
		gluPerspective(90, 1, 1, 5000);
		glMatrixMode(GL_MODELVIEW);
		glLoadIdentity();
		glDisable(GL_SCISSOR_TEST);
		glColorMask(GL_TRUE, GL_TRUE, GL_TRUE, GL_TRUE);
		glDepthMask(GL_TRUE);
		glClearDepth(1);
		glClearColor(0, 0, 0, 0);
		glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);
		const auto random_before = lightning_random_calls;
		draw_lightning_scene_item(item, *image.texture);
		draw_lightning_scene_item(item, *image.texture);
		finish_lightning_batch();
		check(lightning_random_calls == random_before + 6, "Native lightning did not consume three effects samples per ordered draw");
		GLint actual_target, view[4];
		glGetIntegerv(GL_DRAW_FRAMEBUFFER_BINDING, &actual_target);
		glGetIntegerv(GL_VIEWPORT, view);
		check(GLuint(actual_target) == target && view[0] == 3 && view[1] == 5 && view[2] == 48 && view[3] == 43, "Native lightning lost the caller framebuffer or offset canvas");
		std::array<unsigned char, 64 * 64 * 4> pixels;
		glReadPixels(0, 0, 64, 64, GL_RGBA, GL_UNSIGNED_BYTE, pixels.data());
		unsigned changed = 0;
		for (unsigned p = 0; p < 64 * 64; ++p) changed += pixels[p * 4 + 2] != 0;
		check(changed > 0 && changed < 64 * 64, "Native lightning did not draw bounded visible glow");
		std::array<float, 64 * 64> depths;
		glReadPixels(0, 0, 64, 64, GL_DEPTH_COMPONENT, GL_FLOAT, depths.data());
		for (float value : depths) check(value == 1, "Native lightning changed scene depth");
		glBindFramebuffer(GL_FRAMEBUFFER, 0);
		glBindRenderbuffer(GL_RENDERBUFFER, 0);
		glDeleteFramebuffers(1, &target);
		glDeleteTextures(1, &color);
		glDeleteRenderbuffers(1, &scene_depth);
		check(glGetError() == GL_NO_ERROR, "Native lightning scene produced a GL error");
		return pixels;
	};
	const auto expected = draw();
	recreate();
	check(draw() == expected, "Native lightning pixels changed across real context recreation");
	discard_lightning_context(false);
	check(draw() == expected, "Native lightning pixels changed after explicit GPU resource release");
	discard_lightning_context(false);
	const auto border = image.texture->border_handle();
	image.texture.reset();
	check(!glIsTexture(border), "Corona destruction retained its padded mip texture");
	grd_curscreen = nullptr;
	std::cout << "Native lightning scene: original camera path, offset canvas, draw RNG, depth preservation and real context recreation passed\n";
}
