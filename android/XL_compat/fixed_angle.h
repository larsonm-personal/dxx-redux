inline int fixed_vector_dot(const std::array<int, 3> &a, const std::array<int, 3> &b)
{
	const double value = (double(a[0]) * b[0] + double(a[1]) * b[1] + double(a[2]) * b[2]) / 65536.0;
	if (value < INT32_MIN || value > INT32_MAX) throw std::runtime_error("XL vector dot product exceeds fixed range");
	return int(value);
}
// Pinned FixACos, including its zero result at either unit boundary
inline int fixed_normalized_angle(const std::array<int, 3> &a, const std::array<int, 3> &b)
{
	const int dot = fixed_vector_dot(a, b);
	const auto absolute = dot < 0 ? -std::int64_t(dot) : std::int64_t(dot);
	if (absolute >= 65536) return 0;
	const unsigned index = unsigned(absolute) >> 8, fraction = unsigned(absolute) & 255;
	const auto &table = fixed_angle_detail::fixed_acos_table;
	const int delta = int(table[index + 1]) - int(table[index]);
	int angle = int(table[index]) + int(std::floor(double(delta * int(fraction)) / 256.0));
	return dot < 0 ? 32768 - angle : angle;
}
