static void spawn_points_lifecycle_test(const std::filesystem::path &root)
{
	char error[256]{};
	write_spawn_points_fixture(root);
	require(load_base_mission("spawn", error, sizeof(error)), error);
	require(xl_level_supported("neptunxl.rl2", 0), xl_level_rejection());
	require(!xl_level_supported("neptunxl.rl2", 1), "spawn fixture admitted multiplayer");
	StartNewGame(1);
	const int player = ConsoleObject - Objects;
	const auto classic = Player_init[0];
	const auto original_position = ConsoleObject->pos;
	require(!xl_spawn_state_count(), "new level inherited spawn points");
	HUD_clear_messages();
	xl_object_trigger_frame();
	require(!HUD_init_message_literal(HM_DEFAULT, "New spawn points set!"), "object spawn action omitted the source HUD cue");
	require(xl_spawn_state_count() == XL_SPAWN_SLOTS && capture_spawns()[0].segment == 30 && !std::memcmp(&original_position, &ConsoleObject->pos, sizeof(original_position)), "object autoplay failed to set spawns without moving player");
	std::ifstream manifest_file(root / "boost-fixture.json");
	const auto manifest = nlohmann::json::parse(manifest_file);
	const int area = manifest.at("area"), side = manifest.at("side"), child = manifest.at("child"), robot = manifest.at("robot");
	// Cross the real open wall through physics, rather than invoking its action directly
	vms_vector portal, inside, outside;
	compute_center_point_on_side(&portal, &Segments[area], side);
	compute_segment_center(&inside, &Segments[area]);
	compute_segment_center(&outside, &Segments[child]);
	for (auto *point : { &inside, &outside }) {
		vm_vec_sub(point, point, &portal);
		vm_vec_scale(point, F1_0 / 4);
		vm_vec_add2(point, &portal);
	}
	obj_relink(player, area);
	ConsoleObject->pos = inside;
	ConsoleObject->control_type = CT_NONE;
	ConsoleObject->movement_type = MT_PHYSICS;
	ConsoleObject->mtype.phys_info = {};
	ConsoleObject->mtype.phys_info.mass = F1_0;
	vm_vec_sub(&ConsoleObject->mtype.phys_info.velocity, &outside, &inside);
	vm_vec_scale(&ConsoleObject->mtype.phys_info.velocity, i2f(4));
	FrameTime = F1_0 / 4;
	object_move_one(ConsoleObject);
	const auto earned = capture_spawns();
	require(ConsoleObject->segnum == child && earned.size() == XL_SPAWN_SLOTS && earned[0].segment == 60 && earned[1].segment == 84 && earned[2].segment == 30 && earned[15].segment == 60, "real wall crossing failed to configure cyclic spawn points");
	const auto respawn = [&] {
		Players[Player_num].flags &= ~PLAYER_FLAGS_INVULNERABLE;
		Players[Player_num].lives = 5;
		Players[Player_num].shields = F1_0;
		apply_damage_to_player(ConsoleObject, ConsoleObject, i2f(200), 0);
		require(ConsoleObject->flags & OF_SHOULD_BE_DEAD, "lethal damage did not enter death path");
		obj_delete_all_that_should_be_dead();
		require(Player_is_dead, "lethal damage did not start player death");
		DoPlayerDead();
		require(!Player_is_dead && Players[Player_num].lives == 4 && !vm_vec_mag(&ConsoleObject->mtype.phys_info.velocity), "ordinary death did not respawn a fresh ship");
	};
	respawn();
	require(ConsoleObject->segnum == 60 && !std::memcmp(&ConsoleObject->pos, earned[0].position, sizeof(ConsoleObject->pos)) && !std::memcmp(&ConsoleObject->orient, earned[0].orientation, sizeof(ConsoleObject->orient)) && same_spawns(earned, capture_spawns()), "death lost authored spawn transform or persistent configuration");
	char placement_site[] = "spawn lifecycle";
	require(get_seg_masks(&ConsoleObject->pos, ConsoleObject->segnum, ConsoleObject->size, placement_site, 0).sidemask == 0, "spawn fixture does not fit the player sphere");
	FrameTime = F1_0 / 60;
	for (int frame = 0; frame < 60; ++frame) do_physics_sim(ConsoleObject);
	require(ConsoleObject->segnum == 60, "spawn fixture drifted from its safe room");
	// Exact uppercase SPAWN markers override the table; unrelated slots stay stable
	obj_relink(player, 92);
	compute_segment_center(&ConsoleObject->pos, &Segments[92]);
	input_demo_apply_recorded_marker_drop(2, "spawn");
	input_demo_apply_recorded_marker_drop(4, "SPAWN");
	const int lower_marker = MarkerObject[2], named_marker = MarkerObject[4];
	require(lower_marker >= 0 && named_marker >= 0, "spawn marker control failed to create markers");
	const auto marker_position = Objects[named_marker].pos;
	const auto marker_orientation = Objects[named_marker].orient;
	char marker_save[] = "spawn-marker.sav", marker_description[] = "XL named spawn marker";
	stop_time();
	require(state_save_all_sub(marker_save, marker_description), "named spawn marker save failed");
	require(!game_is_time_paused(), "Native save/restore left the simulation paused");
	respawn();
	require(ConsoleObject->segnum == 92 && !std::memcmp(&ConsoleObject->pos, &marker_position, sizeof(marker_position)) && !std::memcmp(&ConsoleObject->orient, &marker_orientation, sizeof(marker_orientation)), "named SPAWN marker did not override authored respawn");
	require(!check_trigger_sub(1, Player_num, 0) && MarkerObject[4] == -1 && MarkerObject[2] == lower_marker && Objects[lower_marker].id == 2, "spawn action failed to remove only the prior SPAWN marker");
	respawn();
	require(ConsoleObject->segnum == 84, "lowercase marker overrode new authored spawn");
	require(state_restore_all_sub(marker_save, 0) && MarkerObject[4] >= 0 && same_spawns(earned, capture_spawns()), "saved marker or authored spawn table was lost");
	respawn();
	require(ConsoleObject->segnum == 92 && !std::memcmp(&ConsoleObject->pos, &marker_position, sizeof(marker_position)), "restored named marker did not govern actual respawn");
	xl_wall_trigger_reset();
	require(!check_trigger_sub(0, Player_num, 1) && same_spawns(earned, capture_spawns()), "authored multi-target spawn reactivation failed");
	require(!check_trigger_sub(4, Player_num, 0) && xl_speed_boost_active(player), "cross-feature boost setup failed");
	require(xl_wall_trigger(5, player, 0) == 1, "delayed spawn ran immediately");
	const auto boosts = capture_boosts();
	char save[] = "spawn-earned.sav", description[] = "Earned XL spawn points";
	stop_time();
	require(state_save_all_sub(save, description), "spawn disk save failed");
	auto *file = PHYSFS_openWrite("spawn-state.bin");
	require(file && xl_wall_trigger_write(file) && PHYSFS_close(file), "spawn trailer write failed");
	const auto user = root.parent_path() / "preview-user";
	std::ifstream encoded_file(user / "spawn-state.bin", std::ios::binary);
	const xl_compat::Bytes encoded{ std::istreambuf_iterator<char>(encoded_file), std::istreambuf_iterator<char>() };
	require(encoded.size() > 16, "missing spawn trailer");
	for (int variant = 0; variant < 13; ++variant) {
		auto block = nlohmann::json::parse(encoded.begin() + 16, encoded.end());
		block["states"][5][0] = 123;
		auto &rows = block["spawns"];
		if (variant == 0) block.erase("spawns");
		if (variant == 1) rows.erase(rows.end() - 1);
		if (variant == 2) rows[0].erase(rows[0].end() - 1);
		if (variant == 3) rows[0][0] = Highest_segment_index + 1;
		if (variant == 4) rows[0][1] = 6;
		if (variant == 5) rows[0][2] = rows[0][2].get<int>() + 1;
		if (variant == 6) rows[0][5] = rows[0][5].get<int>() + 1;
		if (variant == 7) rows[1] = rows[0];
		if (variant == 8) rows[0][2] = UINT64_MAX;
		if (variant == 9) rows[0][0] = nlohmann::json::parse("true");
		if (variant == 10) block["schema"] = 7;
		if (variant == 11) rows = nlohmann::json::object();
		if (variant == 12) rows[0].push_back(0);
		const auto text = block.dump();
		xl_compat::Bytes bad(encoded.begin(), encoded.begin() + 16);
		bad.insert(bad.end(), text.begin(), text.end());
		std::uint32_t checksum = 2166136261u;
		for (unsigned char byte : text) checksum = (checksum ^ byte) * 16777619u;
		for (int byte = 0; byte < 4; ++byte) {
			bad[8 + byte] = static_cast<unsigned char>(text.size() >> (byte * 8));
			bad[12 + byte] = static_cast<unsigned char>(checksum >> (byte * 8));
		}
		write_bytes((user / "spawn-corrupt.bin").string().c_str(), bad);
		file = PHYSFS_openRead("spawn-corrupt.bin");
		xl_trigger_state pending;
		require(file && !xl_wall_trigger_read(file) && PHYSFS_close(file) && same_spawns(earned, capture_spawns()) && same_boosts(boosts, capture_boosts()) && xl_wall_trigger_state(5, &pending) && pending.elapsed == 0, "malformed spawn trailer partially published other feature state");
	}
	require(!std::memcmp(&classic, &Player_init[0], sizeof(classic)), "XL spawn actions modified Redux spawn table");
	require(load_base_mission("d2", error, sizeof(error)) && load_level("d2leva-1.rl2") == 0, "spawn stock recovery failed");
	require(!xl_spawn_state_count(), "XL spawns leaked into stock level");
	const auto stock_position = ConsoleObject->pos;
	input_demo_apply_recorded_marker_drop(4, "SPAWN");
	require(!xl_spawn_apply(Player_num, ConsoleObject - Objects) && !std::memcmp(&stock_position, &ConsoleObject->pos, sizeof(stock_position)), "XL marker override modified Redux player");
	require(state_restore_all_sub(save, 0) && same_spawns(earned, capture_spawns()) && same_boosts(boosts, capture_boosts()), "disk restore through stock lost spawn or boost state");
	respawn();
	require(ConsoleObject->segnum == 60, "restored authored points did not survive actual death");
	// A removed master owner can still change level state, never move its replacement
	require(state_restore_all_sub(save, 0), "removed owner setup restore failed");
	xl_wall_trigger_reset();
	const int robot_segment = Objects[robot].segnum, signature = Objects[robot].signature;
	const auto robot_position = Objects[robot].pos;
	Objects[robot].flags |= OF_SHOULD_BE_DEAD;
	obj_delete_all_that_should_be_dead();
	const int replacement = obj_create(OBJ_POWERUP, POW_ENERGY, robot_segment, &robot_position, &vmd_identity_matrix, F1_0, CT_POWERUP, MT_PHYSICS, RT_NONE);
	require(replacement == robot && Objects[replacement].signature != signature, "spawn removed-owner slot reuse control failed");
	xl_trigger_state pending;
	require(xl_wall_trigger_state(2, &pending) && pending.operated && pending.attached, "removed owner did not schedule its master");
	GameTime64 += i2f(20);
	FrameTime = 0;
	triggers_frame_process();
	require(xl_wall_trigger_state(3, &pending) && pending.operated && pending.attached && same_spawns(earned, capture_spawns()), "nested spawn lost independent delay or removed-owner context");
	GameTime64 += F1_0;
	triggers_frame_process();
	require(capture_spawns()[0].segment == 92 && !std::memcmp(&robot_position, &Objects[replacement].pos, sizeof(robot_position)), "removed-owner descendant failed to configure spawns or moved replacement");
	require(state_restore_all_sub(save, 0), "final spawn restore failed");
	auto invalid = Triggers[0];
	invalid.num_links = 0;
	require(xl_spawn_action(&invalid) && same_spawns(earned, capture_spawns()), "empty spawn action corrupted configuration");
	require(load_level("neptunxl.rl2") == 0 && !xl_spawn_state_count(), "fresh source load retained authored spawn table");
	require(state_restore_all_sub(save, 0), "final earned spawn restore failed");
	std::cout << "XL spawn lifecycle: actual crossing, lethal damage/respawn, marker precedence, removed owner, disk, atomic malformed trailers and Redux isolation passed\n";
}
