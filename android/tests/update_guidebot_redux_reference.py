def extract(source, name):
    """Extract a complete function, ignoring braces inside comments and strings."""
    match = re.search(
        r"^([\w *\t]+\b" + re.escape(name) + r"\([^;]*?\))\s*\{", source, re.M
    )
    if not match:
        raise ValueError(f"Missing reference function: {name}")
    start = match.end() - 1
    tokens = re.finditer(
        r'/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|[{}]',
        source[start:],
        re.S,
    )
    depth = 0
    for token in tokens:
        if token.group() == "{":
            depth += 1
        elif token.group() == "}":
            depth -= 1
            if depth == 0:
                return match.group(1), source[match.start() : start + token.end()]
    raise ValueError(f"Unterminated reference function: {name}")


def rename(source):
    names = [name for group in FUNCTIONS.values() for name in group]
    return re.sub(
        r"\b(" + "|".join(names) + r")\b",
        lambda match: "redux_" + match.group(),
        source,
    )


