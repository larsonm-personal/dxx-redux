def main():
    sources = {
        filename: subprocess.check_output(
            ["git", "show", f"{PIN}:d2/main/{filename}"], cwd=ROOT
        ).decode("utf-8")
        for filename in FUNCTIONS
    }
    parts = [
        extract(sources[filename], name)
        for filename, names in FUNCTIONS.items()
        for name in names
    ]
    escort = sources["escort.c"]
    license_text = escort[: escort.index("*/") + 2]
    includes = "\n".join(f'#include "{name}.h"' for name in HEADERS)
    goal_text = re.search(
        r"static const char \*const Escort_goal_text\[MAX_ESCORT_GOALS\] = \{.*?\};",
        escort,
        re.S,
    )
    if not goal_text:
        raise ValueError("Missing reference goal labels")
    header = (
        "/* Test-only pinned Redux declarations; see guidebot_redux_reference.c */\n"
        '#pragma once\n#include "ai.h"\n'
        + rename("\n".join(signature + ";" for signature, _ in parts))
        + "\n"
    )
    body = (
        license_text
        + f"\n/* Frozen routing oracle from dxx-redux/dxx-redux {PIN}\n"
        " * Only function symbols are prefixed; engine geometry/math are shared\n"
        " * Generated by update_guidebot_redux_reference.py; do not edit this oracle\n"
        " * Fixtures keep paths below the original 200-point temporary capacity */\n"
        + includes
        + PRELUDE
        + "\n"
        + goal_text.group()
        + '\n#include "guidebot_redux_reference.h"\n// clang-format off\n'
        + rename("\n\n".join(function for _, function in parts))
        + "\n// clang-format on\n"
    )
    (ROOT / "android/tests/guidebot_redux_reference.h").write_text(header, encoding="utf-8")
    (ROOT / "android/tests/guidebot_redux_reference.c").write_text(body, encoding="utf-8")


if __name__ == "__main__":
    main()
