"""Regenerate the audited UUD save compatibility registry from conversion outputs."""

import copy
import hashlib
import json
from pathlib import Path
from zipfile import ZipFile

ROOT = Path(__file__).resolve().parents[2]
DESTINATION = ROOT / "android/app/src/main/cpp/shared/mod_save_supported_data.h"
PACKS = ROOT / "game_data/mods/xfing"


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"))


def patch(archive, member):
    with ZipFile(archive) as source:
        return json.loads(source.read(member))


def effect(row):
    return (
        [row[key] for key in ("NumFrames", "FrameTime", "PlayTime", "VclipFlags", "VclipSound")]
        + row["Frames"]
        + [
            row[key]
            for key in (
                "Light",
                "ChangingWall",
                "ChangingObject",
                "Flags",
                "CritClip",
                "DestBm",
                "DestVclip",
                "DestEclip",
                "DestSize",
                "Sound",
            )
        ]
    )


def main():
    result = {"d1": {}, "effects": {}, "ham": {}}
    stock = json.loads((ROOT / "android/tests/mod_save/stock_effects.json").read_text())
    rows = {str(row["Index"]): row for row in stock}

    def add_effect(index, row):
        variants = result["effects"].setdefault(index, [])
        if effect(row) not in variants:
            variants.append(effect(row))

    for index, row in rows.items():
        add_effect(index, row)

    def leaf(path, value):
        if isinstance(value, dict):
            for key, child in value.items():
                leaf(path + "/" + key, child)
        else:
            values = result["ham"].setdefault(path, [])
            if value not in values:
                values.append(value)

    for archive in (
        PACKS / "dxx_tp/tmp/plain_texture_dxa/uud2tp-textures.dxa",
        PACKS / "d2x_sp/uud2sp-sounds.dxa",
    ):
        modified = copy.deepcopy(rows)
        for operation in patch(archive, "patches/d2/ham_patch.rfc6902.json"):
            path, value = operation["path"], operation["value"]
            leaf(path, value)
            if path.startswith("/sections/eclips/"):
                parts = path.split("/")
                index = parts[3]
                if isinstance(value, dict):
                    add_effect(index, value)
                elif operation["op"] != "test" and index in modified:
                    modified[index][parts[4]] = value
        for index, row in modified.items():
            add_effect(index, row)
    for member in ("properties_patch.rfc6902.json", "level_surface_patch.rfc6902.json"):
        path = "patches/d1/" + member
        value = patch(PACKS / "dxx_tp/tmp/plain_texture_dxa/uud1tp-textures.dxa", path)
        result["d1"][path] = hashlib.sha256(canonical(value).encode()).hexdigest()
    text = (
        "/* Generated by android/helpers/generate_mod_save_supported_data.py\n"
        " * Stock evidence: tests/mod_save/stock_effects.json, retail HAM SHA256\n"
        " * 5233242206c677d65db7f075dd61f2b0a1b7bbe8cd65f56d769efaee1cc38b4d */\n"
        'static const char supported_mod_save_data[] = R"modsave(' + canonical(result) + ')modsave";\n'
    )
    if not DESTINATION.exists() or DESTINATION.read_text() != text:
        DESTINATION.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
